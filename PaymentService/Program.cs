using Contracts.Payments;

var builder = WebApplication.CreateBuilder(args);
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen();

var app = builder.Build();

if (app.Environment.IsDevelopment())
{
    app.UseSwagger();
    app.UseSwaggerUI();
}

app.MapPost("/api/payments/process", (ProcessPaymentRequest request) =>
{
    // Fake payment logic
    if (request.Amount <= 0)
    {
        return Results.Ok(new ProcessPaymentResponse(false, string.Empty, "Invalid amount"));
    }

    var transactionId = Guid.NewGuid().ToString("N");
    return Results.Ok(new ProcessPaymentResponse(true, transactionId, "Payment successful"));
});

app.Run();



